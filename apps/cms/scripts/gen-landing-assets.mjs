// Inlines the store screenshots (docs/store-assets) into src/landing/assets.generated.ts so the
// bundled Vercel function can serve them without shipping extra files.
// Re-run after `pnpm store:assets`: node apps/cms/scripts/gen-landing-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../../../docs/store-assets/", import.meta.url);
const files = {
  "screenshot-1.png": "screenshot-1-paragraph-and-exercises.png",
  "screenshot-2.png": "screenshot-2-word-gloss.png",
  "screenshot-3.png": "screenshot-3-progress.png",
};
let out = "// Generated by scripts/gen-landing-assets.mjs — do not edit.\n";
out += "export const LANDING_ASSETS: Record<string, string> = {\n";
for (const [name, src] of Object.entries(files)) {
  out += `  "${name}": "${readFileSync(new URL(src, dir)).toString("base64")}",\n`;
}
out += "};\n";
writeFileSync(new URL("../src/landing/assets.generated.ts", import.meta.url), out);
